"""PDF report generation with ReportLab. Evidence is redacted before rendering."""
import io
from datetime import datetime
from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import mm
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, PageBreak

from app.core.logging_config import redact

SEV_COLORS = {"Critical": "#7f1d1d", "High": "#dc2626", "Medium": "#ea580c", "Low": "#ca8a04", "Informational": "#2563eb"}
SEV_ORDER = ["Critical", "High", "Medium", "Low", "Informational"]


def _p(text, style):
    return Paragraph(escape(redact(str(text or ""))), style)


def build_report(scan, findings, summary) -> bytes:
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=18*mm, rightMargin=18*mm, topMargin=18*mm, bottomMargin=18*mm,
                            title="Web Vulnerability Assessment Report")
    ss = getSampleStyleSheet()
    h1 = ParagraphStyle("h1", parent=ss["Heading1"], textColor=colors.HexColor("#0f172a"))
    h2 = ParagraphStyle("h2", parent=ss["Heading2"], textColor=colors.HexColor("#1e293b"))
    body = ss["BodyText"]
    small = ParagraphStyle("small", parent=body, fontSize=8, textColor=colors.HexColor("#475569"))
    story = []

    # Cover
    story += [Spacer(1, 60*mm), Paragraph("Web Vulnerability Assessment Report", ParagraphStyle("t", parent=h1, fontSize=26)),
              Spacer(1, 8*mm), _p(f"Target: {scan.target.base_url}", h2),
              _p(f"Scan ID: {scan.id}", body),
              _p(f"Generated: {datetime.utcnow():%Y-%m-%d %H:%M} UTC", body),
              Spacer(1, 20*mm),
              _p("Generated by an authorized defensive security assessment tool. Confidential.", small), PageBreak()]

    # Executive summary
    counts = {s: 0 for s in SEV_ORDER}
    for f in findings:
        counts[f.severity.value] += 1
    story += [Paragraph("Executive Summary", h1),
              _p(f"The automated assessment of {scan.target.base_url} discovered {len(findings)} finding(s) across "
                 f"{summary.total_urls if summary else 0} page(s). Severity indicates potential impact; confidence indicates how "
                 f"certain the scanner is. Findings with lower confidence require manual verification.", body), Spacer(1, 6*mm)]

    # Target + config + stats
    cfg = [["Target", scan.target.base_url], ["Max depth", scan.max_depth], ["Max URLs", scan.max_urls],
           ["Request delay (s)", scan.request_delay], ["Modules", ", ".join(scan.modules or [])],
           ["URLs discovered", scan.urls_discovered], ["Parameters found", scan.parameters_found],
           ["Started", scan.started_at], ["Completed", scan.completed_at]]
    t = Table([[Paragraph(escape(str(a)), body), Paragraph(escape(str(b)), body)] for a, b in cfg], colWidths=[45*mm, 120*mm])
    t.setStyle(TableStyle([("GRID", (0, 0), (-1, -1), 0.25, colors.lightgrey), ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#f1f5f9"))]))
    story += [Paragraph("Target Information, Configuration and Statistics", h2), t, Spacer(1, 6*mm)]

    # Severity summary
    sev_table = Table([SEV_ORDER, [counts[s] for s in SEV_ORDER]], colWidths=[33*mm]*5)
    style = [("ALIGN", (0, 0), (-1, -1), "CENTER"), ("GRID", (0, 0), (-1, -1), 0.25, colors.grey), ("TEXTCOLOR", (0, 0), (-1, 0), colors.white)]
    for i, s in enumerate(SEV_ORDER):
        style.append(("BACKGROUND", (i, 0), (i, 0), colors.HexColor(SEV_COLORS[s])))
    sev_table.setStyle(TableStyle(style))
    story += [Paragraph("Severity Summary", h2), sev_table, PageBreak()]

    # Findings overview
    order = {s: i for i, s in enumerate(SEV_ORDER)}
    findings = sorted(findings, key=lambda f: order[f.severity.value])
    rows = [["#", "Type", "Severity", "Confidence", "URL"]]
    for i, f in enumerate(findings, 1):
        rows.append([i, Paragraph(escape(f.type), small), f.severity.value, Paragraph(escape(f.confidence.value), small),
                     Paragraph(escape(f.url[:70]), small)])
    ft = Table(rows, colWidths=[8*mm, 42*mm, 22*mm, 30*mm, 68*mm], repeatRows=1)
    ft.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#0f172a")), ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                            ("GRID", (0, 0), (-1, -1), 0.25, colors.lightgrey), ("FONTSIZE", (0, 0), (-1, -1), 8)]))
    story += [Paragraph("Findings", h1), ft, PageBreak(), Paragraph("Detailed Findings", h1)]

    for i, f in enumerate(findings, 1):
        story += [Paragraph(f"{i}. {escape(f.type)}", h2),
                  _p(f"Severity: {f.severity.value}   |   Confidence: {f.confidence.value}   |   OWASP: {f.owasp_category or 'n/a'}", small),
                  _p(f"URL: {f.url}  ({f.method})" + (f"   Parameter: {f.parameter}" if f.parameter else ""), body),
                  _p(f"Evidence: {f.evidence}", body), _p(f"Description: {f.description}", body),
                  _p(f"Impact: {f.impact}", body), _p(f"Remediation: {f.remediation}", body), Spacer(1, 5*mm)]

    # Remediation recommendations (unique)
    story += [PageBreak(), Paragraph("Remediation Recommendations", h1)]
    for r in sorted({f.remediation for f in findings if f.remediation}):
        story.append(_p("• " + r, body))

    story += [Spacer(1, 8*mm), Paragraph("Limitations", h1),
              _p("Automated scanners cannot understand business logic, may produce false positives and false negatives, and only test "
                 "content reachable by the crawler within configured limits. Manual verification by a qualified analyst is recommended.", body),
              Paragraph("Ethical / Authorization Notice", h1),
              _p("This assessment must only be run against systems you own or have explicit written authorization to test. "
                 "Unauthorized scanning may be illegal.", body)]
    doc.build(story)
    return buf.getvalue()
