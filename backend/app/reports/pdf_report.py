"""
PDF report generation with ReportLab for ZeroTrace.
Includes Website Security Posture, score deductions, coverage metrics, and sanitized evidence.
"""
from __future__ import annotations

import io
from datetime import datetime, timezone
from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import PageBreak, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from app.core.logging_config import redact
from app.services.security_posture import calculate_security_posture

SEV_COLORS = {
    "Critical": "#7f1d1d",
    "High": "#dc2626",
    "Medium": "#ea580c",
    "Low": "#ca8a04",
    "Informational": "#2563eb",
}
SEV_ORDER = ["Critical", "High", "Medium", "Low", "Informational"]


def _p(text, style):
    return Paragraph(escape(redact(str(text or ""))), style)


def build_report(scan, findings, summary) -> bytes:
    buf = io.BytesIO()
    doc = SimpleDocTemplate(
        buf,
        pagesize=A4,
        leftMargin=18 * mm,
        rightMargin=18 * mm,
        topMargin=18 * mm,
        bottomMargin=18 * mm,
        title="ZeroTrace — Web Vulnerability Assessment Report",
        author="ZeroTrace",
    )
    ss = getSampleStyleSheet()
    h1 = ParagraphStyle("h1", parent=ss["Heading1"], textColor=colors.HexColor("#0f172a"), fontSize=16, leading=20)
    h2 = ParagraphStyle("h2", parent=ss["Heading2"], textColor=colors.HexColor("#1e293b"), fontSize=13, leading=16)
    body = ss["BodyText"]
    small = ParagraphStyle("small", parent=body, fontSize=8, textColor=colors.HexColor("#475569"), leading=10)
    emerald = ParagraphStyle("emerald", parent=body, fontSize=11, textColor=colors.HexColor("#059669"), fontName="Helvetica-Bold")
    brand_sub = ParagraphStyle("brand_sub", parent=body, fontSize=13, textColor=colors.HexColor("#475569"))

    story = []

    # Calculate unified security posture
    posture = calculate_security_posture(scan, findings)

    # --- Cover Page ---
    story += [
        Spacer(1, 40 * mm),
        Paragraph("ZeroTrace", ParagraphStyle("brand_title", parent=h1, fontSize=32, leading=38, textColor=colors.HexColor("#0f172a"))),
        Paragraph("Automated Web Vulnerability Scanner", brand_sub),
        Spacer(1, 2 * mm),
        Paragraph("Discover. Analyze. Secure.", emerald),
        Spacer(1, 15 * mm),
        Paragraph("Web Vulnerability Assessment Report", ParagraphStyle("report_title", parent=h1, fontSize=20, leading=24, textColor=colors.HexColor("#1e293b"))),
        Spacer(1, 8 * mm),
        _p(f"Target: {scan.target.base_url}", h2),
        _p(f"Hostname: {posture['hostname']}", body),
        _p(f"Scan ID: {scan.id}", body),
        _p(f"Generated: {datetime.now(timezone.utc):%Y-%m-%d %H:%M} UTC", body),
        Spacer(1, 15 * mm),
    ]

    # Posture quick summary banner on cover
    score_bg = colors.HexColor(posture["rating_color"])
    cover_posture_table = Table(
        [
            [
                Paragraph("<b>SECURITY POSTURE</b>", ParagraphStyle("sp_lbl", parent=small, textColor=colors.white)),
                Paragraph(f"<b>SCORE: {posture['score']} / 100</b>", ParagraphStyle("sp_sc", parent=body, textColor=colors.white)),
                Paragraph(f"<b>RATING: {posture['rating_label']}</b>", ParagraphStyle("sp_rt", parent=body, textColor=colors.white)),
            ]
        ],
        colWidths=[50 * mm, 60 * mm, 64 * mm],
    )
    cover_posture_table.setStyle(
        TableStyle([
            ("BACKGROUND", (0, 0), (-1, -1), score_bg),
            ("ALIGN", (0, 0), (-1, -1), "CENTER"),
            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
            ("TOPPADDING", (0, 0), (-1, -1), 8),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
        ])
    )
    story += [
        cover_posture_table,
        Spacer(1, 25 * mm),
        _p("Generated by ZeroTrace — Automated Web Vulnerability Scanner. Discover. Analyze. Secure. Confidential.", small),
        PageBreak(),
    ]

    # --- Executive Summary & Security Posture ---
    story += [
        Paragraph("Executive Summary & Security Posture", h1),
        _p(
            f"The automated assessment of {scan.target.base_url} discovered {len(findings)} raw finding(s) "
            f"consolidating into {posture['unique_counts']['total']} unique security issue(s) across "
            f"{posture['coverage']['urls_scanned']} scanned URL(s). "
            f"ZeroTrace computed an overall security score of <b>{posture['score']}/100</b> ({posture['rating_label']}).",
            body,
        ),
        Spacer(1, 4 * mm),
    ]

    # Posture Metrics Box
    posture_data = [
        [
            Paragraph("<b>Target Hostname</b>", small),
            Paragraph(escape(posture["hostname"]), small),
            Paragraph("<b>Security Score</b>", small),
            Paragraph(f"<b>{posture['score']} / 100</b>", ParagraphStyle("score_txt", parent=small, textColor=colors.HexColor(posture["rating_color"]), fontName="Helvetica-Bold")),
        ],
        [
            Paragraph("<b>Scan ID</b>", small),
            Paragraph(escape(posture["scan_id"][:18] + "..."), small),
            Paragraph("<b>Rating Status</b>", small),
            Paragraph(f"<b>{posture['rating_label']}</b>", small),
        ],
        [
            Paragraph("<b>Raw Findings</b>", small),
            Paragraph(str(posture["raw_counts"]["total"]), small),
            Paragraph("<b>Unique Findings</b>", small),
            Paragraph(str(posture["unique_counts"]["total"]), small),
        ],
        [
            Paragraph("<b>Confirmed Findings</b>", small),
            Paragraph(str(posture["unique_confirmed_count"]), small),
            Paragraph("<b>Manual Verification Req.</b>", small),
            Paragraph(str(posture["unique_manual_verification_count"]), small),
        ],
    ]
    posture_tbl = Table(posture_data, colWidths=[42 * mm, 45 * mm, 42 * mm, 45 * mm])
    posture_tbl.setStyle(
        TableStyle([
            ("GRID", (0, 0), (-1, -1), 0.25, colors.HexColor("#cbd5e1")),
            ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#f8fafc")),
            ("BACKGROUND", (2, 0), (2, -1), colors.HexColor("#f8fafc")),
            ("TOPPADDING", (0, 0), (-1, -1), 4),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
        ])
    )
    story += [posture_tbl, Spacer(1, 5 * mm)]

    if posture["is_preliminary"]:
        for pr in posture["preliminary_reasons"]:
            story.append(_p(f"⚠️ <b>Preliminary Assessment Notice:</b> {pr}", small))
        story.append(Spacer(1, 3 * mm))

    # --- Severity Distribution (Unique vs Raw) ---
    story += [Paragraph("Severity Distribution (Unique vs Raw)", h2)]
    sev_rows = [["Severity", "Critical", "High", "Medium", "Low", "Informational", "Total"]]
    u_counts = posture["unique_counts"]
    r_counts = posture["raw_counts"]
    sev_rows.append([
        "Unique Issues",
        str(u_counts["critical"]),
        str(u_counts["high"]),
        str(u_counts["medium"]),
        str(u_counts["low"]),
        str(u_counts["informational"]),
        str(u_counts["total"]),
    ])
    sev_rows.append([
        "Raw Occurrences",
        str(r_counts["critical"]),
        str(r_counts["high"]),
        str(r_counts["medium"]),
        str(r_counts["low"]),
        str(r_counts["informational"]),
        str(r_counts["total"]),
    ])
    sev_tbl = Table(sev_rows, colWidths=[38 * mm, 22 * mm, 22 * mm, 24 * mm, 22 * mm, 26 * mm, 20 * mm])
    sev_tbl.setStyle(
        TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#0f172a")),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("ALIGN", (1, 0), (-1, -1), "CENTER"),
            ("GRID", (0, 0), (-1, -1), 0.25, colors.HexColor("#cbd5e1")),
            ("FONTSIZE", (0, 0), (-1, -1), 8),
            ("TOPPADDING", (0, 0), (-1, -1), 4),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
        ])
    )
    story += [sev_tbl, Spacer(1, 6 * mm)]

    # --- Score Deductions ---
    story += [Paragraph("Score Deductions & Reasons", h2)]
    if posture["score_deductions"]:
        ded_rows = [["Finding Type", "Severity", "Confidence", "Instances", "Deduction"]]
        for d in posture["score_deductions"][:12]:
            ded_rows.append([
                Paragraph(escape(d["finding_type"]), small),
                d["severity"],
                Paragraph(escape(d["confidence"]), small),
                str(d["occurrences"]),
                f"-{d['points_deducted']} pts",
            ])
        ded_tbl = Table(ded_rows, colWidths=[55 * mm, 25 * mm, 38 * mm, 24 * mm, 32 * mm], repeatRows=1)
        ded_tbl.setStyle(
            TableStyle([
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#334155")),
                ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                ("GRID", (0, 0), (-1, -1), 0.25, colors.HexColor("#cbd5e1")),
                ("FONTSIZE", (0, 0), (-1, -1), 8),
                ("TOPPADDING", (0, 0), (-1, -1), 3),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
            ])
        )
        story += [ded_tbl, Spacer(1, 6 * mm)]
    else:
        story += [_p("No score deductions were incurred during this scan.", small), Spacer(1, 4 * mm)]

    # --- Target Info, Configuration & Coverage Metrics ---
    story += [Paragraph("Target Configuration & Coverage Limitations", h2)]
    cov = posture["coverage"]
    cfg_data = [
        ["Target URL", scan.target.base_url],
        ["Scan Status", posture["scan_status"]],
        ["Max Depth / Max URLs", f"{cov['max_depth']} / {cov['max_urls']}"],
        ["URLs Scanned / Discovered", f"{cov['urls_scanned']} scanned / {cov['urls_discovered']} discovered"],
        ["Parameters Found", str(cov["parameters_found"])],
        ["Active Modules", ", ".join(cov["modules"]) if cov["modules"] else "All default"],
        ["Scan Started / Completed", f"{scan.started_at or 'n/a'} / {scan.completed_at or 'n/a'}"],
    ]
    cfg_tbl = Table([[Paragraph(escape(str(a)), small), Paragraph(escape(str(b)), small)] for a, b in cfg_data], colWidths=[52 * mm, 122 * mm])
    cfg_tbl.setStyle(
        TableStyle([
            ("GRID", (0, 0), (-1, -1), 0.25, colors.HexColor("#cbd5e1")),
            ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#f1f5f9")),
            ("TOPPADDING", (0, 0), (-1, -1), 3),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
        ])
    )
    story += [cfg_tbl, Spacer(1, 4 * mm)]

    if cov.get("routes_discovered"):
        story += [Paragraph("<b>SPA / Client-Side Route Discovery:</b>", small)]
        route_data = [
            ["Discovered Routes", f"{len(cov.get('routes_discovered', []))} ({', '.join(cov.get('routes_discovered', [])[:8])})"],
            ["Visited Routes", str(len(cov.get("routes_visited", [])))],
            ["Tested Routes", str(len(cov.get("routes_tested", [])))],
            ["Auth-Required Routes", f"{len(cov.get('routes_auth_required', []))} ({', '.join(cov.get('routes_auth_required', [])) if cov.get('routes_auth_required') else 'none'})"],
            ["Failed Routes", str(len(cov.get("routes_failed", [])))],
        ]
        route_tbl = Table([[Paragraph(escape(str(a)), small), Paragraph(escape(str(b)), small)] for a, b in route_data], colWidths=[52 * mm, 122 * mm])
        route_tbl.setStyle(
            TableStyle([
                ("GRID", (0, 0), (-1, -1), 0.25, colors.HexColor("#cbd5e1")),
                ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#f8fafc")),
                ("TOPPADDING", (0, 0), (-1, -1), 2.5),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 2.5),
            ])
        )
        story += [route_tbl, Spacer(1, 4 * mm)]

    if cov.get("limitations"):
        story += [Paragraph("<b>Coverage Constraints & Assessment Scope:</b>", small)]
        for lim in cov["limitations"]:
            story.append(_p(f"• {lim}", small))
        story.append(Spacer(1, 4 * mm))

    story.append(PageBreak())

    # --- Findings Overview ---
    order = {s: i for i, s in enumerate(SEV_ORDER)}
    sorted_findings = sorted(findings, key=lambda f: order.get(_get_sev_val(f), 99))
    rows = [["#", "Type", "Severity", "Confidence", "URL"]]
    for i, f in enumerate(sorted_findings, 1):
        f_sev = _get_sev_val(f)
        f_conf = _get_conf_val(f)
        f_type = getattr(f, "type", "")
        f_url = getattr(f, "url", "")
        rows.append([
            i,
            Paragraph(escape(f_type), small),
            f_sev,
            Paragraph(escape(f_conf), small),
            Paragraph(escape(f_url[:70]), small),
        ])
    ft = Table(rows, colWidths=[8 * mm, 42 * mm, 22 * mm, 30 * mm, 72 * mm], repeatRows=1)
    ft.setStyle(
        TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#0f172a")),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("GRID", (0, 0), (-1, -1), 0.25, colors.lightgrey),
            ("FONTSIZE", (0, 0), (-1, -1), 8),
            ("TOPPADDING", (0, 0), (-1, -1), 3),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
        ])
    )
    story += [Paragraph("Findings Overview", h1), ft, PageBreak(), Paragraph("Detailed Findings", h1)]

    for i, f in enumerate(sorted_findings, 1):
        f_sev = _get_sev_val(f)
        f_conf = _get_conf_val(f)
        f_type = getattr(f, "type", "")
        f_owasp = getattr(f, "owasp_category", None) or "n/a"
        f_url = getattr(f, "url", "")
        f_meth = getattr(f, "method", "GET")
        f_param = getattr(f, "parameter", None)
        f_ev = getattr(f, "evidence", "")
        f_desc = getattr(f, "description", "")
        f_imp = getattr(f, "impact", "")
        f_rem = getattr(f, "remediation", "")

        param_txt = f"   Parameter: {f_param}" if f_param else ""
        story += [
            Paragraph(f"{i}. {escape(f_type)}", h2),
            _p(f"Severity: {f_sev}   |   Confidence: {f_conf}   |   OWASP: {f_owasp}", small),
            _p(f"URL: {f_url}  ({f_meth}){param_txt}", body),
            _p(f"Evidence: {f_ev}", body),
            _p(f"Description: {f_desc}", body),
            _p(f"Impact: {f_imp}", body),
            _p(f"Remediation: {f_rem}", body),
            Spacer(1, 5 * mm),
        ]

    # --- Remediation Recommendations ---
    story += [PageBreak(), Paragraph("Prioritized Remediation Recommendations", h1)]
    if posture["recommendations"]:
        for r in posture["recommendations"]:
            story.append(
                _p(f"• <b>[{r['severity']}] {r['finding_type']}:</b> {r['remediation']}", body)
            )
            story.append(Spacer(1, 2 * mm))
    else:
        story.append(_p("No specific remediations required for current scope.", body))

    story += [
        Spacer(1, 8 * mm),
        Paragraph("ZeroTrace Assessment Limitations", h1),
        _p(
            "Automated vulnerability scanners cannot understand application business logic or complex state workflows, "
            "may report false positives or false negatives, and evaluate only surfaces reachable by the crawler within configured limits. "
            "The ZeroTrace Security Posture Score is based on our proprietary heuristic scoring model and does not constitute an "
            "industry-standard certification, compliance audit, or absolute guarantee of security. "
            "Manual verification by qualified application security analysts is always strongly recommended.",
            body,
        ),
        Spacer(1, 4 * mm),
        Paragraph("Authorization & Ethical Notice", h1),
        _p(
            "This assessment report was generated by ZeroTrace for authorized security testing only. "
            "Scanning systems without prior explicit written authorization may violate applicable laws.",
            body,
        ),
    ]

    doc.build(story)
    return buf.getvalue()


def _get_sev_val(f):
    sev = getattr(f, "severity", "")
    return sev.value if hasattr(sev, "value") else str(sev)


def _get_conf_val(f):
    conf = getattr(f, "confidence", "")
    return conf.value if hasattr(conf, "value") else str(conf)
